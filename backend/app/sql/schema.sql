-- Production PostgreSQL schema, mirrored from app/models.py.
-- These statements create only missing objects; they do not alter or drop existing objects.

-- name: ensure_pgvector_extension
CREATE EXTENSION IF NOT EXISTS vector;

-- name: create_subject
CREATE TABLE IF NOT EXISTS subject (
    subject_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_code VARCHAR(20) NOT NULL UNIQUE,
    subject_name VARCHAR(100) NOT NULL,
    department VARCHAR(100)
);

-- name: create_semester
CREATE TABLE IF NOT EXISTS semester (
    semester_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    semester_number INTEGER NOT NULL CHECK (semester_number BETWEEN 1 AND 8),
    academic_year VARCHAR(9) NOT NULL,
    UNIQUE (semester_number, academic_year)
);

-- name: create_question_type
CREATE TABLE IF NOT EXISTS question_type (
    type_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_name VARCHAR(50) NOT NULL UNIQUE
);

-- name: create_user_account
CREATE TABLE IF NOT EXISTS user_account (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(32) NOT NULL UNIQUE,
    password_hash VARCHAR(256) NOT NULL
);

-- name: create_user_session
CREATE TABLE IF NOT EXISTS user_session (
    session_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL
        REFERENCES user_account(user_id) ON DELETE CASCADE ON UPDATE CASCADE,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMP NOT NULL
);

-- name: create_unit
CREATE TABLE IF NOT EXISTS unit (
    unit_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id INTEGER NOT NULL
        REFERENCES subject(subject_id) ON DELETE CASCADE ON UPDATE CASCADE,
    unit_number INTEGER NOT NULL,
    unit_name VARCHAR(150) NOT NULL,
    UNIQUE (subject_id, unit_number)
);

-- name: create_topic
CREATE TABLE IF NOT EXISTS topic (
    topic_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_id INTEGER NOT NULL
        REFERENCES unit(unit_id) ON DELETE CASCADE ON UPDATE CASCADE,
    topic_name VARCHAR(150) NOT NULL
);

-- name: create_exam_paper
CREATE TABLE IF NOT EXISTS exam_paper (
    paper_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id INTEGER NOT NULL
        REFERENCES subject(subject_id) ON DELETE CASCADE ON UPDATE CASCADE,
    semester_id INTEGER NOT NULL
        REFERENCES semester(semester_id) ON DELETE CASCADE ON UPDATE CASCADE,
    exam_type VARCHAR(20) NOT NULL
        CHECK (exam_type IN ('Internal', 'Mid', 'End', 'Supplementary')),
    total_marks INTEGER NOT NULL CHECK (total_marks > 0)
);

-- name: create_question
CREATE TABLE IF NOT EXISTS question (
    question_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_id INTEGER NOT NULL
        REFERENCES question_type(type_id) ON DELETE RESTRICT ON UPDATE CASCADE,
    question_text TEXT NOT NULL,
    vector_id VARCHAR(100)
);

-- name: create_paper_question
CREATE TABLE IF NOT EXISTS paper_question (
    paper_id INTEGER NOT NULL
        REFERENCES exam_paper(paper_id) ON DELETE CASCADE ON UPDATE CASCADE,
    question_id INTEGER NOT NULL
        REFERENCES question(question_id) ON DELETE CASCADE ON UPDATE CASCADE,
    question_number VARCHAR(10) NOT NULL,
    marks INTEGER NOT NULL CHECK (marks > 0),
    PRIMARY KEY (paper_id, question_id),
    UNIQUE (paper_id, question_number)
);

-- name: create_question_topic
CREATE TABLE IF NOT EXISTS question_topic (
    question_id INTEGER NOT NULL
        REFERENCES question(question_id) ON DELETE CASCADE ON UPDATE CASCADE,
    topic_id INTEGER NOT NULL
        REFERENCES topic(topic_id) ON DELETE CASCADE ON UPDATE CASCADE,
    PRIMARY KEY (question_id, topic_id)
);

-- name: create_question_embedding
CREATE TABLE IF NOT EXISTS question_embedding (
    question_id INTEGER PRIMARY KEY
        REFERENCES question(question_id) ON DELETE CASCADE ON UPDATE CASCADE,
    embedding vector(384) NOT NULL
);

-- name: create_user_session_user_id_index
CREATE INDEX IF NOT EXISTS user_session_user_id_idx ON user_session (user_id);
